(* ======================================================================
   CONTRACT: every law of the project in one theorem, generated by
   quickproof/tools/new_contract.py.

   Proving `suite` makes all laws share one model and one specification
   per function of the code under test.  The statement of `suite` below
   is the generated one: the laws of the contract but x_prim_x25519.
   `suite_x` is the conjunction of the 19 x_ laws,
   proved from the parts of src/proof/.  The 19 short laws are proved by
   area in src/proof/harness/short/ (rp_laws, ae_laws, hs_laws), each
   from one theorem per law in src/proof/harness/<law>/.  Each law is
   also a theorem of its own, with its generated name and statement, in
   src/contracts/laws.v: the x_ laws as projections of `suite_x`, the
   short laws as projections of `suite`.
   ====================================================================== *)

